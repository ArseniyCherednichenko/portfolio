import { AnimatePresence, motion, useReducedMotion } from 'framer-motion'
import { useCallback, useEffect, useId, useMemo, useRef, useState } from 'react'

// PegSolitaire — the old wooden cross board, rebuilt as a real object you play
// by the real rules.
//
// Its own thing in the toys family. Simon is recall, Lights Out is parity,
// Mastermind deduction, Tic-tac-toe a solved game against perfect play; this is
// a solved *puzzle*. You jump one peg orthogonally over a neighbour into the
// empty hole beyond, and the jumped peg is lifted off. Clear the board down and
// the goal is the hardest, cleanest finish there is: a single peg, left standing
// in the centre.
//
// Honest the way the family cares about:
//   • The rules are the real ones and strictly enforced: a move exists only when
//     the source holds a peg, the hole jumped is a peg, and the landing hole two
//     away in a straight line is empty. Nothing else counts as a move, and the
//     board is only ever changed by one.
//   • "Solve it" is not a fake. The standard English board with the centre empty
//     is genuinely solvable to one peg in the centre, and the replayed line is a
//     real 31-move solution — generated by an exhaustive search and verified,
//     move by move, to be legal and to end with exactly one peg, in the middle.
//
// Built without canvas or image: the board is a CSS grid of recessed holes and
// SVG-lit pegs. Selecting a peg lights every legal landing for it; the moving
// peg slides out of its hole and over the one it takes, which fades off the
// board. A real roving-tabindex grid — arrows walk the holes, Enter or Space
// selects a peg and then plays a lit landing, Escape clears the selection, R
// resets — every hole is labelled with its place and contents, and each move,
// the count, and the finish are spoken through a polite live region. Under
// reduced motion the slide and the fades drop: pegs simply appear and vanish,
// and the solver steps through without the travel.

interface PegSolitaireProps {
  /** Size of one grid cell in px. The board is a 7x7 grid of these. */
  cell?: number
  className?: string
}

// The English (cross) board: holes at (r,c) where the row or the column is in
// the middle three. 33 holes in reading order; index 16 is the centre. These,
// and the solution below, were generated and verified together in Node.
const COORDS: readonly (readonly [number, number])[] = [
  [0, 2], [0, 3], [0, 4],
  [1, 2], [1, 3], [1, 4],
  [2, 0], [2, 1], [2, 2], [2, 3], [2, 4], [2, 5], [2, 6],
  [3, 0], [3, 1], [3, 2], [3, 3], [3, 4], [3, 5], [3, 6],
  [4, 0], [4, 1], [4, 2], [4, 3], [4, 4], [4, 5], [4, 6],
  [5, 2], [5, 3], [5, 4],
  [6, 2], [6, 3], [6, 4],
]
const CENTER = 16 // the middle hole, COORDS.length === 33

// (row,col) -> hole index, for neighbour lookups.
const AT = new Map<string, number>()
COORDS.forEach(([r, c], i) => AT.set(`${r},${c}`, i))

// Every legal jump template on the board: from a hole, over an orthogonal
// neighbour, into the hole two away in the same straight line.
interface Move {
  from: number
  over: number
  to: number
}
const DIRS = [
  [-1, 0],
  [1, 0],
  [0, -1],
  [0, 1],
] as const
const MOVES: Move[] = []
COORDS.forEach(([r, c], from) => {
  for (const [dr, dc] of DIRS) {
    const over = AT.get(`${r + dr},${c + dc}`)
    const to = AT.get(`${r + 2 * dr},${c + 2 * dc}`)
    if (over !== undefined && to !== undefined) MOVES.push({ from, over, to })
  }
})
// Moves grouped by their source hole, for quick "what can this peg do" lookups.
const MOVES_FROM: Move[][] = COORDS.map((_, i) => MOVES.filter((m) => m.from === i))

// A real, verified 31-move solution from the standard start (centre empty) to a
// single peg in the centre. Each triple is [from, over, to]. Generated by an
// exhaustive search in Node and checked, move by move, to be legal and to leave
// exactly one peg — at index 16, the middle.
const SOLUTION: readonly (readonly [number, number, number])[] = [
  [4, 9, 16], [7, 8, 9], [0, 3, 8], [2, 1, 0], [9, 8, 7], [6, 7, 8], [10, 5, 2],
  [12, 11, 10], [15, 8, 3], [0, 3, 8], [13, 14, 15], [15, 8, 3], [17, 10, 5],
  [2, 5, 10], [19, 18, 17], [17, 10, 5], [27, 22, 15], [20, 21, 22], [22, 15, 8],
  [3, 8, 15], [15, 16, 17], [24, 17, 10], [5, 10, 17], [26, 25, 24], [23, 24, 25],
  [32, 29, 24], [17, 24, 29], [30, 31, 32], [32, 29, 24], [25, 24, 23], [28, 23, 16],
]

const COL_NAME = ['first', 'second', 'third', 'fourth', 'fifth', 'sixth', 'seventh']
const ROW_NAME = ['top', 'second', 'third', 'middle', 'fifth', 'sixth', 'bottom']
const placeName = (i: number) => {
  const [r, c] = COORDS[i]
  if (i === CENTER) return 'the centre'
  return `${ROW_NAME[r]} row, ${COL_NAME[c]} column`
}

const startBoard = (): boolean[] => COORDS.map((_, i) => i !== CENTER)
const pegsLeft = (b: boolean[]) => b.reduce((n, p) => (p ? n + 1 : n), 0)
const anyMove = (b: boolean[]) =>
  MOVES.some((m) => b[m.from] && b[m.over] && !b[m.to])

export function PegSolitaire({ cell = 46, className = '' }: PegSolitaireProps) {
  const reduce = useReducedMotion()
  const id = useId()

  const [board, setBoard] = useState<boolean[]>(startBoard)
  const [selected, setSelected] = useState<number | null>(null)
  const [focusHole, setFocusHole] = useState(CENTER)
  const [moveCount, setMoveCount] = useState(0)
  const [best, setBest] = useState<number | null>(null)
  // The move that produced the current board, so the landed peg can slide in
  // from the hole it came out of.
  const [last, setLast] = useState<Move | null>(null)
  const [solving, setSolving] = useState(false)

  const holeRefs = useRef<(HTMLButtonElement | null)[]>([])
  const solveTimer = useRef<number | null>(null)

  const left = pegsLeft(board)
  const stuck = !solving && !anyMove(board)
  const finished = stuck && left === 1 && board[CENTER]
  const done = stuck // no legal moves remain

  const clearSolve = () => {
    if (solveTimer.current !== null) {
      window.clearTimeout(solveTimer.current)
      solveTimer.current = null
    }
  }

  // Legal landings for the currently selected peg.
  const targets = useMemo(() => {
    if (selected === null) return new Set<number>()
    const s = new Set<number>()
    for (const m of MOVES_FROM[selected]) {
      if (board[m.from] && board[m.over] && !board[m.to]) s.add(m.to)
    }
    return s
  }, [selected, board])

  const reset = useCallback(() => {
    clearSolve()
    setSolving(false)
    setBoard(startBoard())
    setSelected(null)
    setMoveCount(0)
    setLast(null)
    setFocusHole(CENTER)
  }, [])

  // Apply one legal jump. Returns the next board, or null if the move is not
  // legal on the given board — the board is only ever changed through here.
  const applyMove = useCallback((b: boolean[], m: Move): boolean[] | null => {
    if (!b[m.from] || !b[m.over] || b[m.to]) return null
    const next = b.slice()
    next[m.from] = false
    next[m.over] = false
    next[m.to] = true
    return next
  }, [])

  // Record the best (fewest pegs) finish once a game can go no further.
  useEffect(() => {
    if (!done) return
    setBest((prev) => (prev === null ? left : Math.min(prev, left)))
  }, [done, left])

  useEffect(() => clearSolve, [])

  const jump = useCallback(
    (from: number, to: number) => {
      const m = MOVES_FROM[from].find((mm) => mm.to === to)
      if (!m) return
      setBoard((b) => {
        const next = applyMove(b, m)
        if (!next) return b
        setLast(m)
        setMoveCount((n) => n + 1)
        setSelected(null)
        setFocusHole(to)
        return next
      })
    },
    [applyMove],
  )

  // One click or key-activate on a hole. Picks up a peg, puts it down on a lit
  // landing, or clears the selection.
  const activate = useCallback(
    (i: number) => {
      if (solving) return
      if (selected !== null && targets.has(i)) {
        jump(selected, i)
        return
      }
      if (board[i]) {
        setSelected((cur) => (cur === i ? null : i))
      } else {
        setSelected(null)
      }
    },
    [solving, selected, targets, board, jump],
  )

  const focus = useCallback((i: number) => {
    setFocusHole(i)
    holeRefs.current[i]?.focus()
  }, [])

  const onKeyDown = useCallback(
    (e: React.KeyboardEvent, i: number) => {
      const [r, c] = COORDS[i]
      const go = (dr: number, dc: number) => {
        const n = AT.get(`${r + dr},${c + dc}`)
        if (n !== undefined) focus(n)
      }
      switch (e.key) {
        case 'ArrowRight':
          e.preventDefault(); go(0, 1); break
        case 'ArrowLeft':
          e.preventDefault(); go(0, -1); break
        case 'ArrowDown':
          e.preventDefault(); go(1, 0); break
        case 'ArrowUp':
          e.preventDefault(); go(-1, 0); break
        case 'Enter':
        case ' ':
          e.preventDefault(); activate(i); break
        case 'Escape':
          e.preventDefault(); setSelected(null); break
        case 'r':
        case 'R':
          e.preventDefault(); reset(); break
      }
    },
    [focus, activate, reset],
  )

  // Replay the verified solution from a fresh board, one jump at a time.
  const solve = useCallback(() => {
    clearSolve()
    setSolving(true)
    setSelected(null)
    setBoard(startBoard())
    setMoveCount(0)
    setLast(null)
    const step = reduce ? 90 : 440
    let k = 0
    const tick = () => {
      if (k >= SOLUTION.length) {
        setSolving(false)
        solveTimer.current = null
        return
      }
      const [from, over, to] = SOLUTION[k]
      k++
      setBoard((b) => {
        const next = applyMove(b, { from, over, to })
        if (!next) return b
        setLast({ from, over, to })
        setMoveCount((n) => n + 1)
        setFocusHole(to)
        return next
      })
      solveTimer.current = window.setTimeout(tick, step)
    }
    solveTimer.current = window.setTimeout(tick, step)
  }, [reduce, applyMove])

  const announce = solving
    ? `Solving. ${left} ${left === 1 ? 'peg' : 'pegs'} left.`
    : finished
      ? 'Solved. One peg, left standing in the centre.'
      : done
        ? `No moves left. ${left} ${left === 1 ? 'peg' : 'pegs'} remain.`
        : selected !== null
          ? `${placeName(selected)} selected. ${targets.size} ${targets.size === 1 ? 'landing' : 'landings'}.`
          : `${left} pegs. Your move.`

  const boardPx = cell * 7

  return (
    <div className={`flex flex-col items-center ${className}`}>
      {/* Honest counts: pegs still on the board, jumps played, best finish. */}
      <div className="mb-6 flex items-stretch gap-2.5">
        <Score label="Pegs" value={left} tone="lime" />
        <Score label="Moves" value={moveCount} tone="muted" />
        <Score label="Best left" value={best ?? '--'} tone="muted" />
      </div>

      {/* The board — a 7x7 grid; only the 33 cross holes are rendered. */}
      <div
        role="grid"
        aria-label="Peg solitaire board"
        className="relative rounded-3xl bg-gradient-to-b from-white/[0.05] to-black/40 p-3 ring-1 ring-white/10"
      >
        <div
          className="relative grid"
          style={{
            width: boardPx,
            height: boardPx,
            gridTemplateColumns: `repeat(7, ${cell}px)`,
            gridTemplateRows: `repeat(7, ${cell}px)`,
          }}
        >
          {/* Empty structural cells for the four corners of the 7x7 grid. */}
          {Array.from({ length: 49 }, (_, g) => {
            const r = Math.floor(g / 7)
            const c = g % 7
            const i = AT.get(`${r},${c}`)
            if (i === undefined) return <span key={`gap-${g}`} aria-hidden />
            const peg = board[i]
            const isSel = selected === i
            const isTarget = targets.has(i)
            const slide =
              last && last.to === i
                ? { x: (COORDS[last.from][1] - c) * cell, y: (COORDS[last.from][0] - r) * cell }
                : null
            return (
              <div key={i} className="relative grid place-items-center">
                <button
                  ref={(el) => {
                    holeRefs.current[i] = el
                  }}
                  type="button"
                  role="gridcell"
                  tabIndex={i === focusHole ? 0 : -1}
                  disabled={solving}
                  onFocus={() => setFocusHole(i)}
                  onClick={() => activate(i)}
                  onKeyDown={(e) => onKeyDown(e, i)}
                  aria-label={`${placeName(i)}: ${peg ? 'peg' : 'empty'}${isSel ? ', selected' : ''}${isTarget ? ', a landing for the selected peg' : ''}`}
                  aria-pressed={isSel}
                  className="group relative grid place-items-center rounded-full outline-none focus-visible:ring-2 focus-visible:ring-white/80"
                  style={{ width: cell, height: cell }}
                >
                  {/* The recessed hole. */}
                  <span
                    aria-hidden
                    className={`absolute rounded-full transition-colors ${
                      isTarget
                        ? 'bg-[#DCF87C]/15 ring-2 ring-[#DCF87C]/60'
                        : 'bg-black/50 ring-1 ring-inset ring-white/5'
                    }`}
                    style={{ width: cell * 0.5, height: cell * 0.5 }}
                  />
                  {/* A lit ring on each legal landing for the selected peg. */}
                  {isTarget && !reduce && (
                    <motion.span
                      aria-hidden
                      className="absolute rounded-full ring-2 ring-[#DCF87C]/70"
                      style={{ width: cell * 0.5, height: cell * 0.5 }}
                      animate={{ scale: [1, 1.18, 1], opacity: [0.7, 0.35, 0.7] }}
                      transition={{ duration: 1.6, repeat: Infinity, ease: 'easeInOut' }}
                    />
                  )}
                  <AnimatePresence>
                    {peg && (
                      <motion.span
                        key="peg"
                        aria-hidden
                        className="absolute grid place-items-center rounded-full"
                        style={{
                          width: cell * 0.62,
                          height: cell * 0.62,
                          background:
                            'radial-gradient(circle at 35% 30%, rgba(220,248,124,0.95), rgba(170,205,80,0.9) 55%, rgba(120,150,55,0.95))',
                          boxShadow: isSel
                            ? '0 0 0 2px rgba(220,248,124,0.9), 0 0 14px rgba(220,248,124,0.55)'
                            : '0 1px 2px rgba(0,0,0,0.5), inset 0 1px 2px rgba(255,255,255,0.35)',
                        }}
                        initial={
                          reduce
                            ? { opacity: 1, scale: 1 }
                            : slide
                              ? { x: slide.x, y: slide.y, scale: 1, opacity: 1 }
                              : { scale: 0.4, opacity: 0 }
                        }
                        animate={{ x: 0, y: 0, scale: 1, opacity: 1 }}
                        exit={reduce ? { opacity: 0 } : { scale: 0.3, opacity: 0 }}
                        transition={{
                          duration: reduce ? 0 : 0.3,
                          ease: 'easeOut',
                        }}
                      />
                    )}
                  </AnimatePresence>
                </button>
              </div>
            )
          })}
        </div>
      </div>

      <p id={`${id}-live`} aria-live="polite" className="sr-only">
        {announce}
      </p>

      {/* Status line. */}
      <div className="mt-6 flex min-h-[2rem] items-center text-center">
        {finished ? (
          <span className="font-display text-lg font-semibold tracking-tight text-[#DCF87C]">
            Solved &mdash; one peg, in the centre
          </span>
        ) : done ? (
          <span className="font-display text-lg font-semibold tracking-tight text-white/80">
            No moves left &mdash; {left} {left === 1 ? 'peg' : 'pegs'} remain
          </span>
        ) : solving ? (
          <span className="inline-flex items-center gap-2 text-sm text-white/55">
            <span aria-hidden className="h-1.5 w-1.5 rounded-full bg-[#DCF87C]/70" />
            Replaying a verified solution
          </span>
        ) : selected !== null ? (
          <span className="text-sm text-white/55">
            {targets.size > 0 ? (
              <>Pick a lit hole to jump, or press Escape</>
            ) : (
              <>That peg has no move &mdash; pick another</>
            )}
          </span>
        ) : (
          <span className="text-sm text-white/55">
            Select a peg &mdash; jump over a neighbour into the empty hole beyond
          </span>
        )}
      </div>

      <div className="mt-4 flex flex-wrap items-center justify-center gap-3">
        <button
          type="button"
          onClick={reset}
          className="rounded-full border border-[#DCF87C]/40 bg-[#DCF87C]/10 px-5 py-1.5 text-xs font-semibold text-[#DCF87C] transition hover:bg-[#DCF87C]/20"
        >
          New board
        </button>
        <button
          type="button"
          onClick={solve}
          disabled={solving}
          className={`rounded-full border px-4 py-1.5 text-xs font-medium transition ${
            solving
              ? 'cursor-default border-white/15 bg-white/[0.04] text-white/40'
              : 'border-white/20 bg-white/[0.05] text-white/80 hover:border-white/40 hover:text-white'
          }`}
        >
          {solving ? 'Solving' : 'Solve it'}
        </button>
      </div>

      <p className="mt-5 max-w-sm text-center text-[11px] leading-relaxed text-white/35">
        {finished ? (
          <>The cleanest finish there is &mdash; every other peg jumped off, one left standing in the middle.</>
        ) : (
          <>
            The real rules, strictly kept: jump a peg over a neighbour into the empty hole beyond, and lift the one you
            jumped. &ldquo;Solve it&rdquo; replays a real 31-move line to a single centre peg, found by exhaustive
            search and verified move by move.
          </>
        )}
      </p>
    </div>
  )
}

function Score({ label, value, tone }: { label: string; value: number | string; tone: 'lime' | 'muted' }) {
  return (
    <div className="flex min-w-[4.5rem] flex-col items-center rounded-2xl border border-white/10 bg-white/[0.02] px-4 py-2.5">
      <span
        className={`font-display text-2xl font-bold tabular-nums leading-none ${
          tone === 'lime' ? 'text-[#DCF87C]' : 'text-white/85'
        }`}
      >
        {value}
      </span>
      <span className="mt-1.5 text-[10px] font-semibold uppercase tracking-[0.18em] text-white/40">{label}</span>
    </div>
  )
}
