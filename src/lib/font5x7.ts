/** The glyph for a character, folding lowercase to upper and falling back to a
 * blank cell for anything unmapped — so unknown input never throws. */
export function glyphFor(ch: string): Glyph {
  return FONT[ch] ?? FONT[ch.toUpperCase()] ?? FONT[' ']
}
